"""WoL request #11: the mining techs that never reach plantation-like buildings (read-only).

Usage: python -I tools/wol_mining_report.py <WoL data folder> > docs/wol-mining-report.md

It only reads protoy.xml and techtreey.xml. A WorkRate effect changes one exact rate key of the
gatherers (stock behaviour; docs/wol-requests.md, Q4): a tech on unittype AbstractMine raises only
their AbstractMine rate, and a gatherer that has its own <Rate> for a plantation-like proto (one
that also carries AbstractMine) gathers there at that rate, which the mining tech never touches.
The report lists:
1. the plantation-like protos (AbstractMine, name not starting with "Mine");
2. the gatherers with their own rate for one of them;
3. the techs with a Gather WorkRate effect on AbstractMine, grouped by the plantation-like keys
   (among those of 2) for which the same tech has no matching effect.
"""
import collections
import os
import re
import sys

ATTR = r"""\s*=\s*["']([^"']*)["']"""


def attrs(tag):
    return {k: v for k, v in re.findall(r"(\w+)" + ATTR, tag)}


def types_of(body):
    return set(re.findall(r"<UnitType>\s*([^<\s]+)\s*</UnitType>", body))


def main(argv):
    if len(argv) != 1:
        sys.exit(__doc__)
    folder = argv[0]
    protoy = open(os.path.join(folder, "protoy.xml"), "rb").read().decode("utf-8", "replace")
    techs = open(os.path.join(folder, "techtreey.xml"), "rb").read().decode("utf-8", "replace")

    units = {}
    for m in re.finditer(r"<Unit\s+([^>]*)>(.*?)</Unit>", protoy, re.S):
        units[attrs(m.group(1)).get("name", "?")] = m.group(2)
    plantations = sorted(n for n, b in units.items()
                         if "AbstractMine" in types_of(b) and not n.lower().startswith("mine"))

    gatherers = collections.defaultdict(set)
    for n, b in units.items():
        for t in re.findall(r"<Rate\s+type" + ATTR, b):
            if t in plantations:
                gatherers[n].add(t)
    # Only a proto some gatherer has its own rate for can be missed: elsewhere the gatherers use
    # their AbstractMine rate, which the mining tech raises.
    own = sorted({t for v in gatherers.values() for t in v})

    groups = collections.defaultdict(list)
    count = 0
    for m in re.finditer(r"<Tech\s+([^>]*)>(.*?)</Tech>", techs, re.S):
        name = attrs(m.group(1)).get("name", "?")
        keys = set()
        for head, _ in re.findall(r"<Effect\s+([^>]*)>(.*?)</Effect>", m.group(2), re.S):
            a = attrs(head)
            if a.get("subtype", "").lower() in ("workrate", "workratespecific") and a.get("action", "") == "Gather":
                keys.add(a.get("unittype", ""))
        if "AbstractMine" in keys:
            count += 1
            groups[tuple(p for p in own if p not in keys)].append(name)

    print("# WoL #11: mining techs and plantation-like buildings")
    print()
    print(r"Generated by `tools/wol_mining_report.py` from WoL's `data\protoy.xml` and `data\techtreey.xml`. See")
    print("[wol-requests.md](wol-requests.md), #11 and Q4, for why a mining tech misses these buildings and")
    print("how to fix it in the data: next to each `AbstractMine` effect, the same effect with the")
    print("plantation-like `unittype`, as stock does for `HCRoyalMint`.")
    print()
    print(f"## Plantation-like protos ({len(plantations)})")
    print()
    print("Protos with `AbstractMine` whose name does not start with `Mine`: " + ", ".join(f"`{p}`" for p in plantations)
          + ".")
    print()
    print(f"Of these, some gatherer has its own rate for: " + ", ".join(f"`{p}`" for p in own) + ".")
    print()
    print(f"## Gatherers with their own rate for one of them ({len(gatherers)})")
    print()
    print("| Gatherer | Own rates |")
    print("|---|---|")
    for n in sorted(gatherers):
        print(f"| `{n}` | {', '.join(sorted(gatherers[n]))} |")
    print()
    print(f"## Mining techs ({count}), by the keys they do not boost")
    print()
    for miss, names in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
        print(f"- **Missing {', '.join(miss) or 'nothing'}** ({len(names)}): {', '.join(sorted(names))}.")


if __name__ == "__main__":
    main(sys.argv[1:])
